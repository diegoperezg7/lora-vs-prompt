LABEL_BELOW = {"qwen0.5b-fewshot"}  # keeps neighbouring labels apart


def family(name: str) -> int:
    return 1 if "lora" in name else 2 if "3b" in name else 0


def pct(x: float) -> str:
    return f"{100 * x:.1f}"


def ci(pair) -> str:
    return f"[{100 * pair[0]:.1f}, {100 * pair[1]:.1f}]"


# ---------------------------------------------------------------- cost model


def api_cost_per_1k(prompt_tokens: float, gen_tokens: float) -> dict[str, float]:
    return {
        model: (prompt_tokens * pin + gen_tokens * pout) / 1e6 * 1000 * config.USD_TO_EUR
        for model, (pin, pout) in config.API_PRICES.items()
    }


def break_even(results: dict) -> list[dict]:
    """Documents needed before LoRA's fixed cost is paid back by cheaper inference."""
    test = {n: r["test"] for n, r in results["contenders"].items()}
    rows = []
    label_eur = 800 * config.LABEL_SECONDS_PER_DOC / 3600 * config.HOURLY_LABOUR_EUR
    zs = test.get("qwen1.5b-zeroshot")
    api = api_cost_per_1k(zs["prompt_tokens_mean"], zs["gen_tokens_mean"]) if zs else {}
    for lora, size in (("qwen0.5b-lora", "qwen0.5b"), ("qwen1.5b-lora", "qwen1.5b")):
        if lora not in test or size not in results["training"]:
            continue
        tr = results["training"][size]
        train_eur = tr["train_seconds"] * config.LOCAL_WATTS / 3600 / 1000 * config.EUR_PER_KWH
        lora_cost = test[lora]["eur_per_1k_docs_local"] / 1000
        rivals = {
            n: test[n]["eur_per_1k_docs_local"] / 1000
            for n in ("qwen1.5b-fewshot", "qwen3b-fewshot")
            if n in test
        }
        rivals.update({f"API {m}": v / 1000 for m, v in api.items()})
        for rival, cost in rivals.items():
            saving = cost - lora_cost
            rows.append(
                {
                    "lora": lora,
                    "rival": rival,
                    "rival_eur_per_1k": cost * 1000,
                    "lora_eur_per_1k": lora_cost * 1000,
                    "fixed_compute_eur": train_eur,
                    "fixed_with_labels_eur": train_eur + label_eur,
                    "docs_compute_only": train_eur / saving if saving > 0 else None,
                    "docs_with_labels": (train_eur + label_eur) / saving if saving > 0 else None,
                }
            )
    return rows


# ---------------------------------------------------------------- tables


def tables(results: dict) -> str:
    c = results["contenders"]
    names = [x.name for x in config.CONTENDERS if x.name in c]
    out = [
        "# Results",
        "",
        "Generated by `make report` from `results/metrics.json`. 95% intervals are"
        f" percentile bootstraps over documents ({config.BOOTSTRAP_SAMPLES} resamples, seed {config.SEED}).",
        "",
    ]

    titles = {
        "test": "Test set: unseen layouts, vendors and wording",
        "hard": "Hard set: two more unseen layouts, heavy OCR, traps over-sampled",
    }
    sampled = [x for x in config.CONTENDERS if x.name in c and x.sample]
    for split, title in titles.items():
        out += [
            f"## {title}",
            "",
            "| Contender | n | Exact match | Macro-F1 (category) | Mean field acc. | JSON valid | p50 / p95 latency"
            " | Gen tok/s | Prompt tokens | Peak mem | Local EUR / 1k docs |",
            "|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        for n in names:
            t = c[n][split]
            out.append(
                f"| `{n}` | {t['n']} | {pct(t['exact_match'])} {ci(t['ci']['exact_match'])} | {pct(t['macro_f1'])} {ci(t['ci']['macro_f1'])}"
                f" | {pct(t['mean_field_accuracy'])} | {pct(t['json_valid'])} | {t['latency_p50_s']:.2f} s / {t['latency_p95_s']:.2f} s"
                f" | {t['gen_tps_median']:.0f} | {t['prompt_tokens_mean']:.0f} | {t['peak_memory_gb']:.2f} GB"
                f" | {t['eur_per_1k_docs_local']:.4f} |"
            )
        out.append("")
    for x in sampled:
        out += [
            f"`{x.name}` is scored on a seeded subsample of {x.sample} documents per split, stratified by"
            " category, to save compute; its intervals are wider accordingly.",
            "",
        ]

    if results.get("paired"):
        out += [
            "## Paired differences (percentage points, 95% paired bootstrap)",
            "",
            "Same documents for both sides; against `qwen3b-fewshot` that is its 100-document subsample.",
            "",
            "| LoRA | minus | Split | n | Exact match | Category accuracy |",
            "|---|---|---|---|---|---|",
        ]
        for r in results["paired"]:
            fmt = lambda t: f"{100 * t[0]:+.1f} [{100 * t[1]:+.1f}, {100 * t[2]:+.1f}]"  # noqa: E731
            out.append(
                f"| `{r['a']}` | `{r['b']}` | {r['split']} | {r['n']} | {fmt(r['exact'])} | {fmt(r['category_ok'])} |"
            )
        out.append("")

    out += [
        "## Seen vs unseen layouts (exact match %)",
        "",
        "Dev reuses the training layouts, vendors and wording on new documents. Test and hard share none of them"
        " with train (see `data/stats.json` for the n-gram overlap check).",
        "",
        "| Contender | Dev (seen) | Test (unseen) | Hard (unseen + traps) | Dev to test (pts) |",
        "|---|---|---|---|---|",
    ]
    for n in names:
        d, t, h = (c[n][s]["exact_match"] if s in c[n] else None for s in ("dev", "test", "hard"))
        gap = f"{100 * (t - d):+.1f}" if d is not None else "-"
        out.append(f"| `{n}` | {pct(d) if d is not None else 'not run'} | {pct(t)} | {pct(h)} | {gap} |")

    for split in ("test", "hard"):
        out += [
            "",
            f"## Field accuracy on {split} (%)",
            "",
            "| Contender | category | " + " | ".join(FIELDS) + " |",
            "|---|" + "---|" * (len(FIELDS) + 1),
        ]
        for n in names:
            t = c[n][split]
            out.append(
                f"| `{n}` | {pct(t['category_accuracy'])} | "
                + " | ".join(pct(t["field_accuracy"][f]) for f in FIELDS)
                + " |"
            )

    for split in ("test", "hard"):
        tags = sorted({k for n in names for k in c[n][split]["slices"]})
        out += [
            "",
            f"## Slices on {split} (exact match %)",
            "",
            "| Slice | n | " + " | ".join(f"`{n}`" for n in names) + " |",
            "|---|---|" + "---|" * len(names),
        ]
        for tag in tags:
            full = next(n for n in names if not config.BY_NAME[n].sample)
            nn = c[full][split]["slices"].get(tag, {}).get("n", 0)
            vals = [
                pct(c[n][split]["slices"][tag]["exact_match"]) if tag in c[n][split]["slices"] else "-"
                for n in names
            ]
            out.append(f"| {tag} | {nn} | " + " | ".join(vals) + " |")

    if results["training"]:
        out += [
            "",
            "## LoRA training",
            "",
            "| Adapter | Base model | Train time | Peak mem | Trained tokens | Final train loss"
            " | Final dev loss | Selected checkpoint (dev loss) | Adapter size |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for name, tr in results["training"].items():
            cur = tr["curves"]
            out.append(
                f"| `{name}` | `{tr['model']}` | {tr['train_seconds'] / 60:.1f} min | {tr['peak_memory_gb']:.2f} GB"
                f" | {tr['trained_tokens']:,} | {cur['train'][-1]['train_loss']:.4f} | {cur['val'][-1]['val_loss']:.4f}"
                f" | {tr['selected_checkpoint']} ({tr['selected_val_loss']:.4f}) | {tr['adapter_mb']} MB |"
            )
        out += ["", "Loss by iteration (train loss is the mean over the 10 iterations before the mark):", ""]
        adapters = list(results["training"])
        out += [
            "| Iteration | " + " | ".join(f"`{a}` train | `{a}` dev" for a in adapters) + " |",
            "|---|" + "---|---|" * len(adapters),
        ]
        val_iters = [v["iteration"] for v in results["training"][adapters[0]]["curves"]["val"]]
        for it in val_iters:
            cells = []
            for a in adapters:
                cur = results["training"][a]["curves"]
                v = next((x["val_loss"] for x in cur["val"] if x["iteration"] == it), None)
                t = next((x["train_loss"] for x in cur["train"] if x["iteration"] == it + 1), None)
                cells += [f"{t:.4f}" if t is not None else "-", f"{v:.4f}" if v is not None else "-"]
            out.append(f"| {it + 1 if it else 0} | " + " | ".join(cells) + " |")
        hp = config.LORA
        out += [
            "",
            f"Hyperparameters: rank {hp['lora_parameters']['rank']}, scale {hp['lora_parameters']['scale']},"
            f" dropout {hp['lora_parameters']['dropout']}, {hp['num_layers']} layers, Adam lr {hp['learning_rate']},"
            f" batch {hp['batch_size']}, {hp['iters']} iterations, prompt masked, seed {hp['seed']}.",
        ]

    be = break_even(results)
    if be:
        label_eur = 800 * config.LABEL_SECONDS_PER_DOC / 3600 * config.HOURLY_LABOUR_EUR
        out += [
            "",
            "## Break-even volume",
            "",
            f"Local cost assumes {config.LOCAL_WATTS:.0f} W while generating and {config.EUR_PER_KWH} EUR/kWh."
            f" Labelling 800 training documents at {config.LABEL_SECONDS_PER_DOC} s each and"
            f" {config.HOURLY_LABOUR_EUR:.0f} EUR/h adds {label_eur:.0f} EUR. API prices are list prices in USD"
            f" converted at {config.USD_TO_EUR}, applied to the zero-shot prompt length (estimate).",
            "",
            "| LoRA | vs | Rival EUR / 1k | LoRA EUR / 1k | Docs to repay training energy | Docs to repay training + labels |",
            "|---|---|---|---|---|---|",
        ]
        for r in be:
            fmt = lambda v: "never (rival is cheaper)" if v is None else f"{v:,.0f}"  # noqa: E731
            out.append(
                f"| `{r['lora']}` | {r['rival']} | {r['rival_eur_per_1k']:.4f} | {r['lora_eur_per_1k']:.4f}"
                f" | {fmt(r['docs_compute_only'])} | {fmt(r['docs_with_labels'])} |"
            )
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------- figures


def _style(ax, th):
    ax.set_facecolor("none")
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(th["grid"])
    ax.tick_params(colors=th["muted"], labelsize=9)
    ax.grid(True, color=th["grid"], linewidth=0.6)
    ax.set_axisbelow(True)
    ax.xaxis.label.set_color(th["muted"])
    ax.yaxis.label.set_color(th["muted"])
    ax.title.set_color(th["text"])


def _save(fig, name: str, theme: str) -> None:
    config.FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    fig.savefig(config.FIGURES_DIR / f"{name}-{theme}.png", dpi=180, transparent=True, bbox_inches="tight")
    plt.close(fig)


def fig_quality_latency(results: dict, theme: str) -> None:
    th = THEMES[theme]
    c = results["contenders"]
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.6), sharey=True)
    for ax, split, title in zip(
        axes,
        ("test", "hard"),
        ("Test: unseen layouts", "Hard: unseen layouts, heavy OCR, traps"),
        strict=True,
    ):
        _style(ax, th)
        seen = set()
        for x in config.CONTENDERS:
            if x.name not in c:
                continue
            t = c[x.name][split]
            f = family(x.name)
            lo, hi = t["ci"]["exact_match"]
            y = 100 * t["exact_match"]
            ax.errorbar(
                t["latency_p50_s"],
                y,
                yerr=[[y - 100 * lo], [100 * hi - y]],
                fmt="o",
                ms=8,
                color=th["series"][f],
                ecolor=th["series"][f],
                elinewidth=1.5,
                capsize=0,
                label=FAMILIES[f] if f not in seen else None,
                zorder=3,
            )
            seen.add(f)
            if x.retry_of:  # sits on top of its base contender; labelled with it
                continue
            label = x.name + (" (and -retry)" if any(y.retry_of == x.name for y in config.CONTENDERS) else "")
            ax.annotate(
                label,
                (t["latency_p50_s"], y),
                xytext=(8, -13) if x.name in LABEL_BELOW else (8, 4),
                textcoords="offset points",
                fontsize=8,
                color=th["text"],
            )
        ax.set_xscale("log")
        ax.set_xticks([0.5, 1, 2, 4, 8])
        ax.xaxis.set_major_formatter(matplotlib.ticker.FuncFormatter(lambda v, _: f"{v:g} s"))
        ax.xaxis.set_minor_formatter(matplotlib.ticker.NullFormatter())
        ax.set_xlim(0.5, 12)
        ax.set_xlabel("p50 latency per document (log; local cost is proportional)")
        ax.set_ylim(0, 100)
        ax.set_title(title, loc="left", fontsize=11.5, fontweight="bold", color=th["text"])
    axes[0].set_ylabel("exact match, % (95% CI)")
    leg = axes[0].legend(loc="upper left", frameon=False, fontsize=8.5)
    for text in leg.get_texts():
        text.set_color(th["text"])
    _save(fig, "quality-vs-latency", theme)


def fig_loss(results: dict, theme: str) -> None:
    th = THEMES[theme]
    tr = results["training"]
    if not tr:
        return
    fig, axes = plt.subplots(1, len(tr), figsize=(4.4 * len(tr), 3.4), sharey=True)
    axes = np.atleast_1d(axes)
    for ax, (name, t) in zip(axes, tr.items(), strict=True):
        _style(ax, th)
        trn, val = t["curves"]["train"], t["curves"]["val"]
        ax.plot(
            [p["iteration"] for p in trn],
            [p["train_loss"] for p in trn],
            color=th["series"][1],
            lw=2,
            label="train",
        )
        ax.plot(
            [p["iteration"] for p in val],
            [p["val_loss"] for p in val],
            color=th["series"][0],
            lw=2,
            marker="o",
            ms=4,
            label="validation (dev)",
        )
        best = min(val, key=lambda p: p["val_loss"])
        ax.plot(
            [best["iteration"]],
            [best["val_loss"]],
            "o",
            ms=11,
            mfc="none",
            mec=th["text"],
            mew=1.5,
            label="selected checkpoint",
        )
        ax.set_yscale("log")
        ax.set_title(
            f"{name}  ({t['train_seconds'] / 60:.1f} min)",
            loc="left",
            fontsize=11,
            fontweight="bold",
            color=th["text"],
        )
        ax.set_xlabel("iteration")
    axes[0].set_ylabel("loss (log scale)")
    leg = axes[-1].legend(frameon=False, fontsize=9, loc="upper right")
    for text in leg.get_texts():
        text.set_color(th["text"])
    _save(fig, "loss-curves", theme)


def fig_confusion(results: dict, theme: str, names: list[str]) -> None:
    th = THEMES[theme]
    c = results["contenders"]
    names = [n for n in names if n in c]
    fig, axes = plt.subplots(1, len(names), figsize=(6.2 * len(names), 5.4))
    axes = np.atleast_1d(axes)
    cols = CATEGORIES + [INVALID]
    for ax, n in zip(axes, names, strict=True):
        m = np.array(c[n]["test"]["confusion"], dtype=float)
        norm = m / m.sum(axis=1, keepdims=True)
        ax.imshow(norm, cmap="Blues", vmin=0, vmax=1, aspect="auto")
        for i in range(m.shape[0]):
            for j in range(m.shape[1]):
                if m[i, j]:
                    ax.text(
                        j,
                        i,
                        int(m[i, j]),
                        ha="center",
                        va="center",
                        fontsize=8,
                        color="#ffffff" if norm[i, j] > 0.55 else "#0b0b0b",
                    )
        ax.set_xticks(
            range(len(cols)),
            [SHORT[x] for x in cols],
            rotation=45,
            ha="right",
            fontsize=8.5,
            color=th["muted"],
        )
        ax.set_yticks(range(len(CATEGORIES)), [SHORT[x] for x in CATEGORIES], fontsize=8.5, color=th["muted"])
        ax.set_xlabel("predicted", color=th["muted"])
        ax.set_ylabel("true", color=th["muted"])
        ax.set_title(
            f"{n}  (macro-F1 {pct(c[n]['test']['macro_f1'])}, n = {c[n]['test']['n']})",
            loc="left",
            fontsize=11,
            fontweight="bold",
            color=th["text"],
        )
        for s in ax.spines.values():
            s.set_visible(False)
    _save(fig, "confusion", theme)


def fig_seen_unseen(results: dict, theme: str) -> None:
    th = THEMES[theme]
    c = results["contenders"]
    names = [x.name for x in config.CONTENDERS if x.name in c]
    splits = [
        ("dev", "dev: seen layouts", 0),
        ("test", "test: unseen", 1),
        ("hard", "hard: unseen + heavy OCR + traps", 2),
    ]
    fig, ax = plt.subplots(figsize=(10, 4))
    _style(ax, th)
    ax.grid(axis="x", visible=False)
    x = np.arange(len(names))
    w = 0.26
    for k, (split, label, color) in enumerate(splits):
        pts = [(i, 100 * c[n][split]["exact_match"]) for i, n in enumerate(names) if split in c[n]]
        xs = np.array([i for i, _ in pts]) + (k - 1) * (w + 0.02)
        vals = [v for _, v in pts]
        ax.bar(xs, vals, w, color=th["ramp"][color], label=label)
        for xi, v in zip(xs, vals, strict=True):
            ax.text(xi, v + 1.5, f"{v:.0f}", ha="center", fontsize=7.5, color=th["muted"])
    ax.set_xticks(x, names, rotation=20, ha="right", fontsize=8.5)
    ax.set_ylim(0, 108)
    ax.set_ylabel("exact match, %")
    ax.set_title(
        "Seen vs unseen document layouts", loc="left", fontsize=12, fontweight="bold", color=th["text"]
    )
    leg = ax.legend(frameon=False, fontsize=9, loc="upper left", ncols=3)
    for text in leg.get_texts():
        text.set_color(th["text"])
    _save(fig, "seen-vs-unseen", theme)


def build_report(results: dict) -> None:
    config.RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    (config.RESULTS_DIR / "results.md").write_text(tables(results))
    # Same base model, same 300 documents: the confusion pair isolates what the adapter changes.
    confusion_pair = ["qwen1.5b-fewshot", "qwen1.5b-lora"]
    for theme in THEMES:
        plt.rcParams["font.family"] = ["Inter", "Helvetica Neue", "Arial", "DejaVu Sans"]
        fig_quality_latency(results, theme)
        fig_loss(results, theme)
        fig_confusion(results, theme, confusion_pair)
        fig_seen_unseen(results, theme)
